#!/bin/bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export CLAUDE_CONFIG_DIR="$SCRIPT_DIR/.claude-judge-runtime"
mkdir -p "$CLAUDE_CONFIG_DIR"
export CLAUDE=${CLAUDE:-~/.local/bin/claude}

CLAUDE_OPTS="--print --verbose --output-format stream-json --dangerously-skip-permissions --setting-sources project --model opus"

if [ -f judge_prompt.md ]; then
    echo "Using judge_prompt.md"
    JUDGE_PROMPT="$(cat judge_prompt.md)"
elif [ -n "${JUDGE_PROMPT:-}" ]; then
    echo "Using JUDGE_PROMPT env var"
else
    echo "Using default judge prompt"
    JUDGE_PROMPT="You are evaluating code generated by an AI coding agent. Review the code in this project directory and the session logs.

Score the generated code on the following rubric. For each dimension, assign an integer score from 1 (poor) to 5 (excellent):

- readability: How easy is the code to read and understand? Consider naming, structure, and clarity.
- idiomatic_style: Does the code follow language conventions and best practices?
- error_handling: Does the code handle edge cases and errors appropriately?
- efficiency: Is the code efficient in terms of time and space complexity?

Respond with ONLY a JSON object (no markdown fences, no extra text) in this exact format:
{
  \"readability\": <1-5>,
  \"idiomatic_style\": <1-5>,
  \"error_handling\": <1-5>,
  \"efficiency\": <1-5>,
  \"overall_notes\": \"<brief explanation of scores>\"
}"
fi

cd project
$CLAUDE $CLAUDE_OPTS "$JUDGE_PROMPT" | tee ../judge_output.json

cd ..
python3 parse_judge.py
